function decode(bytes){const utf8=bytes.toString('utf8');return utf8.includes('\ufffd')?new TextDecoder('gb18030').decode(bytes):utf8}
function scrub(text){return text.replace(/https?:\/\/[^\s\x1b]+/g,raw=>{try{const u=new URL(raw);u.search='';u.hash='';return u.href}catch{return '[URL omitted]'}}).replace(/((?:token|secret|api[_-]?key|authorization)\s*[:=]\s*)[^\s,]+/gi,'$1[redacted]')}
function launchCli(argv){
  const opts={cwd:root,env,windowsHide:true,stdio:['ignore','pipe','pipe'],shell:false}
  if(/\.(?:cmd|bat)$/i.test(cli)){
    for(const a of argv)assert.ok(!/[\r\n"%!^&|<>]/.test(a),'CLI 参数含 shell 元字符')
    return spawn(process.env.ComSpec??'cmd.exe',['/d','/s','/c','""'+cli+'" '+argv.map(a=>'"'+a+'"').join(' ')+'"'],{...opts,windowsVerbatimArguments:true})
  }
  return /\.mjs$/i.test(cli)?spawn(process.execPath,[cli,...argv],opts):spawn(cli,argv,opts)
}
async function cliRun(argv,label,timeout=120000){
  shutdown.signal.throwIfAborted()
  cliChild=launchCli(argv);const child=cliChild;let output=''
  child.stdout.on('data',b=>{output=(output+decode(b)).slice(-50000)});child.stderr.on('data',b=>{output=(output+decode(b)).slice(-50000)})
  const abort=()=>stop(child);shutdown.signal.addEventListener('abort',abort,{once:true})
  const timer=setTimeout(()=>stop(child),timeout)
  try{
    const code=await new Promise((resolve,reject)=>{child.once('error',reject);child.once('close',resolve)})
    await writeFile(path.join(artifacts,label+'.log'),scrub(output))
    assert.equal(code,0,label+' 失败（或超时）；见脱敏日志')
    return output
  }finally{clearTimeout(timer);shutdown.signal.removeEventListener('abort',abort);cliChild=undefined}
}
